// Generates the merc-watch-<key> cron function folders into infra/monitors/out/functions/<slug>/
// (config.json, index.ts, handler.gen.js). Self-contained ESM, no Node built-ins, like the handler bundles.
//   pnpm --dir infra/monitors build
import { build } from "esbuild";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { WATCHES, WATCH_KEYS, type WatchKey } from "./watches.ts";
import { watchSlug } from "./monitors.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUT = join(HERE, "../out/functions");
export const BANNER = "// GENERATED by `pnpm --dir infra/monitors build` from infra/monitors/src/{entry,watches}.ts. Do not edit.";

export async function bundleText(key: WatchKey): Promise<string> {
  const r = await build({
    entryPoints: [join(HERE, "entry.ts")], bundle: true, format: "esm", platform: "neutral", target: "es2020",
    mainFields: ["module", "main"], legalComments: "none", banner: { js: BANNER }, write: false, logLevel: "silent",
    define: { MERC_WATCH_KEY: JSON.stringify(key) },
  });
  return r.outputFiles![0]!.text;
}

export function configJson(key: WatchKey) {
  const w = WATCHES[key];
  return {
    kind: "cron", name: watchSlug(key),
    description: `Merc monitor watch '${key}' (WP-QA-02, REQ-OPS-003): ${w.contract}. Fails the run on a breach so the merc-${key} CronFunctionFailure monitor fires. Source: infra/monitors/src/watches.ts`,
    timeout_ms: 30000,
    cron_schedules: [{ cron_expression: w.cron, timezone: "Europe/Athens", params: {}, enabled: true }],
  };
}

export const INDEX_TS = `// merc-watch wrapper. Logic: Merc monorepo infra/monitors/src/watches.ts, bundled into ./handler.gen.js. Edit there.
import { handle } from "./handler.gen.js";

async function userFunction(context: any): Promise<any> {
  return handle(context);
}
`;

export async function writeAll(keys: WatchKey[] = WATCH_KEYS): Promise<string[]> {
  const out: string[] = [];
  for (const key of keys) {
    const dir = join(OUT, watchSlug(key));
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "config.json"), JSON.stringify(configJson(key), null, 2) + "\n");
    writeFileSync(join(dir, "index.ts"), INDEX_TS);
    writeFileSync(join(dir, "handler.gen.js"), await bundleText(key));
    out.push(dir);
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const d of await writeAll()) console.log(`built ${d}`);
}
