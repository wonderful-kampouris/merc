/**
 * Regenerates src/generated/* from spec/contracts (run after `python3 -I spec/_build/build.py`).
 * Output: schemas.ts (raw JSON schemas), seed.ts (seed rows), types.ts (TS types).
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

type Json = any; // eslint-disable-line @typescript-eslint/no-explicit-any

const here = dirname(fileURLToPath(import.meta.url));
const contractsDir = resolve(process.env.MERC_CONTRACTS_DIR ?? join(here, "../../../spec/contracts"));
const outDir = join(here, "../src/generated");
if (!existsSync(contractsDir)) throw new Error(`contracts dir not found: ${contractsDir}`);
mkdirSync(outDir, { recursive: true });

const readJson = (p: string): Json => JSON.parse(readFileSync(p, "utf8"));
const listJson = (sub: string): string[] =>
  readdirSync(join(contractsDir, sub)).filter((f) => f.endsWith(".json") && !f.startsWith("_")).sort();

// ---- load ---------------------------------------------------------------
const defs = readJson(join(contractsDir, "_defs.json")).$defs as Record<string, Json>;
const functions: Record<string, Json> = {};
for (const f of listJson("functions")) {
  const d = readJson(join(contractsDir, "functions", f));
  functions[d.slug] = d;
}
const events: Record<string, Json> = {};
for (const f of listJson("events")) {
  const d = readJson(join(contractsDir, "events", f));
  events[d.type] = { type: d.type, payload: d.payload };
}
const llm: Record<string, Json> = {};
for (const f of listJson("llm")) {
  const d = readJson(join(contractsDir, "llm", f));
  for (const k of ["name", "profile", "used_by", "purpose", "rules", "eval_set", "input", "output"]) {
    if (!(k in d)) throw new Error(`llm/${f}: missing ${k}`);
  }
  llm[d.name] = {
    name: d.name, profile: d.profile, used_by: d.used_by, purpose: d.purpose, rules: d.rules, eval_set: d.eval_set,
    input: d.input, output: d.output,
  };
}
const seedOrder: string[] = readJson(join(contractsDir, "seed", "_order.json"));
const seed: Record<string, Json[]> = {};
for (const t of seedOrder) seed[t] = readJson(join(contractsDir, "seed", `${t}.json`));

// ---- type emitter -------------------------------------------------------
const pascal = (s: string): string =>
  s.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0]!.toUpperCase() + w.slice(1)).join("");
/** `Error` would shadow the global, so the def is exported as ApiError. */
const defName = (n: string): string => (n === "Error" ? "ApiError" : n);
const refName = (ref: string): string => {
  const m = /#\/\$defs\/(.+)$/.exec(ref);
  if (!m) throw new Error(`unsupported $ref ${ref}`);
  if (!(m[1]! in defs)) throw new Error(`unresolved $ref ${ref}`);
  return defName(m[1]!);
};
const KNOWN = new Set(["type", "properties", "additionalProperties", "required", "format", "items", "$ref", "enum", "anyOf"]);
const key = (k: string): string => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k));

function toTs(s: Json, ind = ""): string {
  if (s === true || s === undefined || (typeof s === "object" && Object.keys(s).length === 0)) return "unknown";
  for (const k of Object.keys(s)) if (!KNOWN.has(k)) throw new Error(`unsupported schema keyword ${k}`);
  if (s.$ref) return refName(s.$ref);
  if (s.anyOf) return s.anyOf.map((x: Json) => toTs(x, ind)).join(" | ");
  if (s.enum) return s.enum.map((v: Json) => JSON.stringify(v)).join(" | ");
  switch (s.type) {
    case "string": return "string";
    case "integer":
    case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": {
      const t = toTs(s.items, ind);
      return /[|&]/.test(t) ? `Array<${t}>` : `${t}[]`;
    }
    case "object": {
      const props: Record<string, Json> = s.properties ?? {};
      const req = new Set<string>(s.required ?? []);
      const names = Object.keys(props);
      if (names.length === 0) return s.additionalProperties === false ? "Record<string, never>" : "Record<string, unknown>";
      const inner = ind + "  ";
      const lines = names.map((n) => `${inner}${key(n)}${req.has(n) ? "" : "?"}: ${toTs(props[n], inner)};`);
      if (s.additionalProperties !== false) lines.push(`${inner}[key: string]: unknown;`);
      return `{\n${lines.join("\n")}\n${ind}}`;
    }
    default: throw new Error(`unsupported type ${JSON.stringify(s.type)}`);
  }
}
const decl = (name: string, s: Json): string => {
  const t = toTs(s);
  return t.startsWith("{") ? `export interface ${name} ${t}\n` : `export type ${name} = ${t};\n`;
};

const out: string[] = ["// GENERATED by scripts/generate.ts from spec/contracts. Do not edit.\n", "// ---- _defs ----"];
for (const [n, s] of Object.entries(defs)) out.push(decl(defName(n), s));

const slugs = Object.keys(functions).sort();
out.push("// ---- functions ----");
for (const slug of slugs) {
  const f = functions[slug];
  out.push(`/** ${f.method} ${slug} (gate: ${f.gate ?? "-"}; callers: ${(f.callers ?? []).join(", ")}) */`);
  out.push(decl(`${pascal(slug)}Request`, f.request));
  out.push(decl(`${pascal(slug)}Response`, f.response));
}
out.push(`export type FunctionSlug =\n${slugs.map((s) => `  | ${JSON.stringify(s)}`).join("\n")};\n`);
out.push(`export interface FunctionRequestMap {\n${slugs.map((s) => `  ${JSON.stringify(s)}: ${pascal(s)}Request;`).join("\n")}\n}\n`);
out.push(`export interface FunctionResponseMap {\n${slugs.map((s) => `  ${JSON.stringify(s)}: ${pascal(s)}Response;`).join("\n")}\n}\n`);
out.push(`export const FUNCTION_METHODS = {\n${slugs.map((s) => `  ${JSON.stringify(s)}: ${JSON.stringify(functions[s].method)},`).join("\n")}\n} as const;\n`);

const evTypes = Object.keys(events).sort();
out.push("// ---- events (merc-live) ----");
for (const t of evTypes) out.push(decl(`${pascal(t)}Payload`, events[t].payload));
out.push(`export type EventType =\n${evTypes.map((s) => `  | ${JSON.stringify(s)}`).join("\n")};\n`);
out.push(`export interface EventPayloadMap {\n${evTypes.map((s) => `  ${JSON.stringify(s)}: ${pascal(s)}Payload;`).join("\n")}\n}\n`);
out.push(`/** WebSocket envelope: {type, at, payload}. */\nexport interface MercEvent<T extends EventType = EventType> {\n  type: T;\n  at: string;\n  payload: EventPayloadMap[T];\n}\n`);

const llmNames = Object.keys(llm).sort();
out.push("// ---- llm structured schemas ----");
for (const n of llmNames) {
  out.push(decl(`${pascal(n)}LlmInput`, llm[n].input));
  out.push(decl(`${pascal(n)}LlmOutput`, llm[n].output));
}
out.push(`export type LlmSchemaName =\n${llmNames.map((s) => `  | ${JSON.stringify(s)}`).join("\n")};\n`);
out.push(`export interface LlmInputMap {\n${llmNames.map((s) => `  ${JSON.stringify(s)}: ${pascal(s)}LlmInput;`).join("\n")}\n}\n`);
out.push(`export interface LlmOutputMap {\n${llmNames.map((s) => `  ${JSON.stringify(s)}: ${pascal(s)}LlmOutput;`).join("\n")}\n}\n`);
out.push(
  `/** Contract metadata per LLM schema: purpose, rules for the prompt, eval set path, model profile, callers. */\n` +
    `export interface LlmContractMeta {\n  name: LlmSchemaName;\n  profile: string;\n  used_by: readonly string[];\n` +
    `  purpose: string;\n  rules: readonly string[];\n  eval_set: string;\n}\n`,
);
out.push(
  `export const LLM_META: { readonly [N in LlmSchemaName]: LlmContractMeta } = {\n${llmNames
    .map((n) => {
      const { name, profile, used_by, purpose, rules, eval_set } = llm[n];
      return `  ${JSON.stringify(n)}: ${JSON.stringify({ name, profile, used_by, purpose, rules, eval_set })},`;
    })
    .join("\n")}\n};\n`,
);
out.push(`export type DefName =\n${Object.keys(defs).map((s) => `  | ${JSON.stringify(s)}`).join("\n")};\n`);

writeFileSync(join(outDir, "types.ts"), out.join("\n"));

const header = "// GENERATED by scripts/generate.ts from spec/contracts. Do not edit.\n";
writeFileSync(
  join(outDir, "schemas.ts"),
  header +
    `/* eslint-disable */\nexport const defs: Record<string, any> = ${JSON.stringify(defs)};\n` +
    `export const functions: Record<string, any> = ${JSON.stringify(functions)};\n` +
    `export const events: Record<string, any> = ${JSON.stringify(events)};\n` +
    `export const llm: Record<string, any> = ${JSON.stringify(llm)};\n`,
);
writeFileSync(
  join(outDir, "seed.ts"),
  header +
    `export const seedOrder: string[] = ${JSON.stringify(seedOrder)};\n` +
    `export const seed: Record<string, Record<string, unknown>[]> = ${JSON.stringify(seed)};\n`,
);
console.log(
  `generated from ${contractsDir}: defs=${Object.keys(defs).length} functions=${slugs.length} ` +
    `events=${evTypes.length} llm=${llmNames.length} seedTables=${seedOrder.length} ` +
    `seedRows=${Object.values(seed).reduce((a, r) => a + r.length, 0)}`,
);
