#!/usr/bin/env node
// Vendors @merc/contracts (packages/contracts/src) and spec/contracts/app/app.json into
// src/contracts/, and writes the app's role catalog (from app.json) into ../wonderful.json.
// The server-side App build only sees this git repo, so the contracts must live inside it.
// Run from app/: `pnpm sync-contracts` (after `pnpm -C packages/contracts build` at the repo root).
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appDir = resolve(here, "..");
const root = resolve(appDir, "../..");
const src = join(root, "packages/contracts/src");
const out = join(appDir, "src/contracts");

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "generated"), { recursive: true });
const banner = "// GENERATED by app/scripts/sync-contracts.mjs from packages/contracts/src. Do not edit.\n";
for (const rel of [...readdirSync(src).filter((f) => f.endsWith(".ts")), ...readdirSync(join(src, "generated")).map((f) => `generated/${f}`)]) {
  writeFileSync(join(out, rel), banner + readFileSync(join(src, rel), "utf8"));
}
const appJsonPath = join(root, "spec/contracts/app/app.json");
copyFileSync(appJsonPath, join(out, "app.json"));

/** app.json roles -> Wonderful app role catalog (permission_grants with all/relation scopes). */
const app = JSON.parse(readFileSync(appJsonPath, "utf8"));
const catalog = {
  permissions: app.permissions.map(({ key, resource, action, relations }) => ({ key, resource, action, relations })),
  roles: Object.entries(app.roles).map(([name, r]) => ({
    name,
    permission_grants: [
      ...r.all.map((permission) => ({ permission, scope: { type: "all" } })),
      ...Object.entries(r.relation).flatMap(([relation, ps]) => ps.map((permission) => ({ permission, scope: { type: "relation", relation } }))),
    ],
  })),
  default_role: app.default_role,
  workspace_admin_role: app.workspace_admin_role,
  audience_roles: { anonymous: [], workspace_members: [app.workspace_admin_role] /* demo: every workspace member (judges included) gets the full app */, app_editors: [app.workspace_admin_role] },
};
const manifestPath = join(appDir, "../wonderful.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
manifest.roles = catalog;
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
console.log(`synced contracts to ${out}; wrote ${catalog.roles.length} roles / ${catalog.permissions.length} permissions to wonderful.json`);
