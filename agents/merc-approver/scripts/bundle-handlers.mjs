// Bundles the three backing handlers (shared/handlers/src: approver-brief, approval-decide, manager-call-outcome)
// into lib/handlers.gen.js for the merc-approver tools (REQ-CORE-004: one implementation, many entries).
// @merc/core is NOT bundled: every import of shared/core/src is rewritten to the agent's Shared Library copy
// (../shared_lib/utils/merc_core), so tools and handlers share ONE core instance (errors, validation, me()).
//   node agents/merc-approver/scripts/bundle-handlers.mjs          # write lib/handlers.gen.js
//   node agents/merc-approver/scripts/bundle-handlers.mjs --check  # exit 1 if the committed bundle is stale
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const AGENT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = resolve(AGENT, "../..");
const CORE = join(ROOT, "shared/core/src");
const HANDLERS = join(ROOT, "shared/handlers/src");
const OUT = join(AGENT, "lib/handlers.gen.js");
const require = createRequire(join(ROOT, "shared/handlers/package.json"));
const { build } = require("esbuild");

export const SLUGS = ["approver-brief", "approval-decide", "manager-call-outcome"];
const BANNER = "// GENERATED by agents/merc-approver/scripts/bundle-handlers.mjs from shared/handlers/src. Do not edit.\n// @merc/core is imported from the Shared Library (shared_lib/utils/merc_core), not bundled.";

const coreToSharedLib = {
  name: "core-to-shared-lib",
  setup(b) {
    b.onResolve({ filter: /core\/src/ }, (args) => {
      const abs = resolve(args.resolveDir, args.path);
      if (!abs.startsWith(CORE)) return null;
      const sub = relative(CORE, abs).split(sep).join("/").replace(/\.ts$/, "");
      return { path: `../shared_lib/utils/merc_core/${sub}`, external: true };
    });
  },
};

export async function bundleText() {
  const contents = [
    `export { makeImpl as makeApproverBrief, spokenBrief } from "./approver-brief";`,
    `export { makeImpl as makeApprovalDecide } from "./approval-decide";`,
    `export { makeImpl as makeManagerCallOutcome } from "./manager-call-outcome";`,
  ].join("\n");
  const r = await build({
    stdin: { contents, resolveDir: HANDLERS, sourcefile: "merc-approver-handlers.ts", loader: "ts" },
    bundle: true, format: "esm", platform: "neutral", target: "es2020", mainFields: ["module", "main"],
    legalComments: "none", banner: { js: BANNER }, write: false, logLevel: "silent", plugins: [coreToSharedLib],
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await bundleText();
  if (process.argv.includes("--check")) {
    const ok = existsSync(OUT) && readFileSync(OUT, "utf8") === text;
    console.log(ok ? "lib/handlers.gen.js is fresh" : "lib/handlers.gen.js is STALE: run scripts/bundle-handlers.mjs");
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log(`bundled lib/handlers.gen.js (${(text.length / 1024).toFixed(0)} KB) from ${SLUGS.join(", ")}`);
}
