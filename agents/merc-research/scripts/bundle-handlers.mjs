// Bundles scripts/handlers-entry.ts (shared/handlers + shared/core + contract schemas) into lib/handlers.gen.js,
// a self-contained ESM file the tools import, so the agent repo builds on the platform without the monorepo.
//   node agents/merc-research/scripts/bundle-handlers.mjs          # write
//   node agents/merc-research/scripts/bundle-handlers.mjs --check  # exit 1 when lib/handlers.gen.js is stale
import { build } from "../../../shared/handlers/node_modules/esbuild/lib/main.js";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "../lib/handlers.gen.js");
const BANNER = "// GENERATED by agents/merc-research/scripts/bundle-handlers.mjs from shared/handlers/src + shared/core. Do not edit.";

export async function bundleText() {
  const r = await build({
    entryPoints: [join(here, "handlers-entry.ts")], bundle: true, format: "esm", platform: "neutral", target: "es2020",
    absWorkingDir: join(here, "../../.."), mainFields: ["module", "main"], legalComments: "none", banner: { js: BANNER }, write: false, logLevel: "silent",
  });
  return r.outputFiles[0].text;
}

const text = await bundleText();
if (process.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (cur !== text) { console.error("lib/handlers.gen.js is stale: run node agents/merc-research/scripts/bundle-handlers.mjs"); process.exit(1); }
  console.log("lib/handlers.gen.js is fresh");
} else {
  writeFileSync(OUT, text);
  console.log(`bundled lib/handlers.gen.js (${(text.length / 1024).toFixed(0)} KB)`);
}
