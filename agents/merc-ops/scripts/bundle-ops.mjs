// Bundles the merc-ops tool backend (shared/handlers/src/summary-data.ts runForOps + shared/core + the shared/llm
// number check) into lib/ops.gen.js, self-contained (no Shared Library needed). REQ-CORE-004: the tool runs the
// SAME summary-data impl as the deployed function.
//   node agents/merc-ops/scripts/bundle-ops.mjs          # write lib/ops.gen.js
//   node agents/merc-ops/scripts/bundle-ops.mjs --check  # exit 1 if the committed bundle is stale
import { createRequire } from "node:module";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const AGENT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = resolve(AGENT, "../..");
const OUT = join(AGENT, "lib/ops.gen.js");
const require = createRequire(join(ROOT, "shared/handlers/package.json"));
const { build } = require("esbuild");
const BANNER = "// GENERATED by agents/merc-ops/scripts/bundle-ops.mjs from shared/handlers/src/summary-data.ts + shared/core + shared/llm. Do not edit.";

export async function bundleText() {
  const contents = [
    `export { runForOps } from "./handlers/src/summary-data";`,
    `export { createDb } from "./core/src/index";`,
    `export { unknownNumbers } from "./llm/src/evidence";`,
  ].join("\n");
  const r = await build({
    stdin: { contents, resolveDir: join(ROOT, "shared"), sourcefile: "merc-ops-backend.ts", loader: "ts" },
    bundle: true, format: "esm", platform: "neutral", target: "es2020", mainFields: ["module", "main"],
    legalComments: "none", banner: { js: BANNER }, write: false, logLevel: "silent", absWorkingDir: ROOT,
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await bundleText();
  if (process.argv.includes("--check")) {
    const ok = existsSync(OUT) && readFileSync(OUT, "utf8") === text;
    console.log(ok ? "lib/ops.gen.js is fresh" : "lib/ops.gen.js is STALE: run scripts/bundle-ops.mjs");
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log(`bundled lib/ops.gen.js (${(text.length / 1024).toFixed(0)} KB)`);
}
