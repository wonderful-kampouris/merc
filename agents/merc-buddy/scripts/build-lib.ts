// WP-BUD-01: bundles the shared handlers (shared/handlers/src/<slug>.ts + @merc/core + shared/llm + shared/live)
// that back the merc-buddy tools into ONE self-contained ESM file, lib/merc.gen.js, so every tool runs the
// exact same impl as its Wonderful Function (REQ-CORE-004) without importing anything outside the agent repo.
//
//   node --experimental-strip-types --no-warnings agents/merc-buddy/scripts/build-lib.ts
//
// Why a bundle and not shared_lib/utils/merc_core: the handlers also need shared/llm and shared/live, which are
// not in the Shared Library, and the shared_lib copy of @merc/core lags the monorepo contracts. One bundle keeps
// handler and core from the same source tree (one copy of MercError, validators and contracts).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const AGENT = join(here, "..");
export const ROOT = join(AGENT, "../..");
const HANDLERS = join(ROOT, "shared/handlers/src");
const CORE = join(ROOT, "shared/core/src/index.ts");
const LLM = join(ROOT, "shared/llm/src/index.ts");
export const OUT = join(AGENT, "lib/merc.gen.js");
export const OUT_DTS = join(AGENT, "lib/merc.gen.d.ts");
export const BANNER = "// GENERATED by agents/merc-buddy/scripts/build-lib.ts from shared/handlers + shared/core. Do not edit.";

export interface ToolSpec { name: string; function: string; inject: string[]; parameters: any; description: string; say?: string }
export function toolSpecs(): ToolSpec[] {
  const agent = JSON.parse(readFileSync(join(ROOT, "spec/contracts/agents/merc-buddy.json"), "utf8"));
  return (agent.tools as string[]).map((t) => JSON.parse(readFileSync(join(ROOT, `spec/contracts/tools/merc-buddy/${t}.json`), "utf8")));
}

/** Handlers whose exported `impl` is not the tool path; the entry builds the tool impl from their factory. */
const CUSTOM: Record<string, (path: string) => string> = {
  "visit-card-get": (p) => `import { makeImpl as cardMake, PITCH_INSTRUCTIONS as cardRules } from ${JSON.stringify(p)};
// Tool path: same impl, merc-write pitch; Context Hub passages are skipped (no context.api in agent tools).
export const visit_card_get_impl = cardMake({ pitch: (input) => callStructured("visit_card_pitch", input, { instructions: cardRules }), kb: async () => [] });`,
  // visit-update records caller "buddy" on its AI actions when called from the tool.
  "visit-update": (p) => `export { buddyImpl as visit_update_impl } from ${JSON.stringify(p)};`,
};

export const exportName = (slug: string) => `${slug.replace(/-/g, "_")}_impl`;

export function entrySource(): { source: string; present: string[]; missing: string[] } {
  const slugs = [...new Set(toolSpecs().map((t) => t.function))].sort();
  const present: string[] = [], missing: string[] = [];
  const lines = [
    `export { runAsTool, secretString, globalString, callerFromTool, MercError } from ${JSON.stringify(CORE)};`,
    `import { callStructured } from ${JSON.stringify(LLM)};`,
  ];
  for (const slug of slugs) {
    const p = join(HANDLERS, `${slug}.ts`);
    if (!existsSync(p)) { missing.push(slug); continue; }
    present.push(slug);
    lines.push(CUSTOM[slug] ? CUSTOM[slug](p) : `export { impl as ${exportName(slug)} } from ${JSON.stringify(p)};`);
  }
  for (const slug of missing) lines.push(`export const ${exportName(slug)} = null; // TODO: shared/handlers/src/${slug}.ts does not exist yet`);
  lines.push(`export const PRESENT_HANDLERS = ${JSON.stringify(present)};`, `export const MISSING_HANDLERS = ${JSON.stringify(missing)};`);
  return { source: lines.join("\n"), present, missing };
}

export function dtsSource(): string {
  const slugs = [...new Set(toolSpecs().map((t) => t.function))].sort();
  return [
    BANNER,
    "export type AnyImpl = (inv: { req: any; db: any; me: any; platform: any }) => Promise<any>;",
    "export interface ToolContextIn { metadata?: any; tables: any; secrets?: any; globals?: any; workspaceId?: string | null }",
    "export declare function runAsTool(slug: string, impl: AnyImpl, ctx: ToolContextIn, params: unknown, key: string, opts?: { checkResponse?: boolean }): Promise<any>;",
    "export declare function secretString(platform: { secrets?: any }, name: string): string | null;",
    "export declare function globalString(platform: { globals?: any }, name: string): string | null;",
    "export declare function callerFromTool(ctx: { metadata?: any }, key: string, now?: number): { kind: string; appUserId: string; orgId: string };",
    "export declare class MercError extends Error { code: string; details: Record<string, unknown> | null }",
    ...slugs.map((s) => `export declare const ${exportName(s)}: AnyImpl | null;`),
    "export declare const PRESENT_HANDLERS: string[];",
    "export declare const MISSING_HANDLERS: string[];",
    "",
  ].join("\n");
}

export async function bundleText(): Promise<string> {
  const require = createRequire(join(ROOT, "shared/handlers/package.json"));
  const { build } = require("esbuild");
  const { source } = entrySource();
  const r = await build({
    stdin: { contents: source, resolveDir: HANDLERS, sourcefile: "merc-buddy-entry.ts", loader: "ts" },
    bundle: true, format: "esm", platform: "neutral", target: "es2020", mainFields: ["module", "main"],
    absWorkingDir: ROOT, legalComments: "none", banner: { js: BANNER }, write: false, logLevel: "silent",
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await bundleText();
  writeFileSync(OUT, text);
  writeFileSync(OUT_DTS, dtsSource());
  const { present, missing } = entrySource();
  console.log(`bundled lib/merc.gen.js (${(text.length / 1024).toFixed(0)} KB): ${present.length} handlers, missing: ${missing.join(", ") || "none"}`);
}
