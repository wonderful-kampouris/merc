// WP-BUD-01: generates tools/<tool>/index.ts and skills/<skill>/skill.json from the contracts
// (spec/contracts/tools/merc-buddy/*.json + spec/contracts/agents/merc-buddy.json), so the agent's tool list,
// parameters and injected values match the contract exactly (REQ-BUD-003). Skill prompt.md files are hand-written.
//
//   node --experimental-strip-types --no-warnings agents/merc-buddy/scripts/gen-tools.ts
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { AGENT, ROOT, exportName, toolSpecs, type ToolSpec } from "./build-lib.ts";

export const GEN_BANNER = "// GENERATED by agents/merc-buddy/scripts/gen-tools.ts from spec/contracts/tools/merc-buddy. Do not edit.";
const ATTACH: Record<string, "resolved" | "card" | "debrief"> = { resolve_account: "resolved", get_visit_card: "card", log_visit: "debrief" };

const fnContract = (slug: string) => JSON.parse(readFileSync(join(ROOT, `spec/contracts/functions/${slug}.json`), "utf8"));

/** Contract inject list reduced to the request fields the function accepts (caller is always kept). */
export function effectiveInject(t: ToolSpec): { inject: string[]; dropped: string[] } {
  const props = fnContract(t.function).request?.properties ?? {};
  const inject: string[] = [], dropped: string[] = [];
  for (const raw of t.inject) {
    const name = raw.replace(/\?$/, "");
    const ok = name === "caller" ? true
      : name === "device_location" ? "lat" in props && "lng" in props
      : name.includes("=") ? name.split("=")[0] in props
      : name in props;
    (ok ? inject : dropped).push(raw);
  }
  return { inject, dropped };
}

const unNull = (sch: any): { sch: any; nullable: boolean } => {
  if (Array.isArray(sch?.anyOf)) {
    const rest = sch.anyOf.filter((x: any) => x?.type !== "null");
    if (rest.length === 1 && rest.length < sch.anyOf.length) return { sch: { ...rest[0], description: sch.description ?? rest[0].description }, nullable: true };
  }
  return { sch, nullable: false };
};

const hint = (sch: any): string | null => {
  const bits = [sch.description, sch.format === "uuid" ? "UUID taken from an earlier tool result" : null, sch.format === "date" ? "YYYY-MM-DD" : null, sch.format === "date-time" ? "ISO 8601 date-time" : null].filter(Boolean);
  return bits.length ? bits.join("; ") : null;
};

/** JSON schema -> @wonderful/types `s` expression. */
export function sExpr(raw: any): string {
  const { sch } = unNull(raw);
  let e: string;
  if (Array.isArray(sch.enum) && sch.enum.every((v: unknown) => typeof v === "string")) e = `s.enum(${sch.enum.map((v: string) => JSON.stringify(v)).join(", ")})`;
  else if (sch.type === "string") e = "s.string()";
  else if (sch.type === "number" || sch.type === "integer") e = "s.number()";
  else if (sch.type === "boolean") e = "s.boolean()";
  else if (sch.type === "array") e = `s.array(${sExpr(sch.items ?? {})})`;
  else if (sch.type === "object") e = objExpr(sch);
  else e = "s.any()";
  const d = hint(sch);
  return d ? `${e}.describe(${JSON.stringify(d)})` : e;
}
export function objExpr(sch: any, indent = ""): string {
  const req = new Set<string>(sch.required ?? []);
  const fields = Object.entries(sch.properties ?? {}).map(([k, v]) => {
    const x = sExpr(v);
    return `${indent}  ${k}: ${req.has(k) ? x : `s.optional(${x})`},`;
  });
  return fields.length ? `s.object({\n${fields.join("\n")}\n${indent}})` : "s.object({})";
}

/** skill.json parameter mirror. */
export function paramMirror(t: ToolSpec) {
  const req = new Set<string>(t.parameters.required ?? []);
  return Object.entries(t.parameters.properties ?? {}).map(([name, v]: [string, any]) => {
    const { sch } = unNull(v);
    const type = Array.isArray(sch.enum) ? "enum" : sch.type === "integer" ? "number" : sch.type === "object" ? "json" : sch.type ?? "json";
    const p: Record<string, unknown> = { name, type, required: req.has(name), is_exposed_to_llm: true };
    const d = hint(sch); if (d) p.description = d;
    if (type === "enum") p.enum_values = sch.enum;
    if (type === "array") p.items = sch.items ?? {};
    return p;
  });
}

export function toolSource(t: ToolSpec): string {
  const { inject } = effectiveInject(t);
  const spec = { tool: t.name, slug: t.function, inject, ...(ATTACH[t.name] ? { attach: ATTACH[t.name] } : {}) };
  const desc = [t.description, t.say ? `After the call: ${t.say}` : ""].filter(Boolean).join(" ");
  return `${GEN_BANNER}
// Backing function: fn:${t.function} (same impl as the Wonderful Function, REQ-CORE-004).
// Injected by code, never by the model: ${t.inject.join(", ")}.
import { s, w } from "@wonderful/types/schema";
import { ${exportName(t.function)} as impl } from "../../lib/merc.gen.js";
import { runTool, type ToolSpec } from "../../lib/runtime";

export const SPEC: ToolSpec = ${JSON.stringify(spec)};

const params = ${objExpr(t.parameters)};

export default w.tool({
  name: ${JSON.stringify(t.name)},
  description: ${JSON.stringify(desc)},
  params,
  handler: async (ctx: any, input: any) => runTool(ctx, SPEC, impl, input),
});
`;
}

/** LLM-backed handlers get 30 s, others 12 s; writes (POST) are not cut off by barge-in. */
const SLOW = new Set(["debrief-process", "ask-crm", "visit-card-get", "prospect-search", "briefing-get", "eod-summary", "discount-request", "candidate-add", "escalate", "approval-resolve"]);
export function toolConfig(t: ToolSpec) {
  const post = fnContract(t.function).method === "POST";
  return { timeout: SLOW.has(t.function) ? 30000 : 12000, is_interruptible: !post };
}

export interface SkillSpec { name: string; trigger: string; tools: string[]; priority?: string; behavior?: string }
export function skillSpecs(): SkillSpec[] {
  return JSON.parse(readFileSync(join(ROOT, "spec/contracts/agents/merc-buddy.json"), "utf8")).skills;
}
const titleCase = (s: string) => s.split("_").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");

export function skillJson(sk: SkillSpec, byName: Map<string, ToolSpec>): string {
  const tools: Record<string, unknown> = {};
  for (const name of sk.tools) {
    const t = byName.get(name)!;
    tools[name] = { type: "programmable", parameters: paramMirror(t), config: toolConfig(t) };
  }
  return JSON.stringify({ name: sk.name, display_name: titleCase(sk.name), description: `Use when: ${sk.trigger}.${sk.behavior ? ` ${sk.behavior}` : ""}`, prompts: { skill: "prompt.md" }, tools }, null, 2) + "\n";
}

export function generate(write = true): Record<string, string> {
  const specs = toolSpecs();
  const byName = new Map(specs.map((t) => [t.name, t]));
  const files: Record<string, string> = {};
  for (const t of specs) files[`tools/${t.name}/index.ts`] = toolSource(t);
  for (const sk of skillSpecs()) files[`skills/${sk.name}/skill.json`] = skillJson(sk, byName);
  if (write) for (const [rel, text] of Object.entries(files)) {
    const p = join(AGENT, rel);
    mkdirSync(join(p, ".."), { recursive: true });
    writeFileSync(p, text);
  }
  return files;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop()!)) {
  const files = generate();
  const missingPrompts = skillSpecs().filter((s) => !existsSync(join(AGENT, `skills/${s.name}/prompt.md`))).map((s) => s.name);
  const dropped = toolSpecs().map((t) => [t.name, effectiveInject(t).dropped] as const).filter(([, d]) => d.length);
  console.log(`generated ${Object.keys(files).length} files; skills without prompt.md: ${missingPrompts.join(", ") || "none"}`);
  for (const [n, d] of dropped) console.log(`  ${n}: inject not accepted by the function request, dropped: ${d.join(", ")}`);
}
