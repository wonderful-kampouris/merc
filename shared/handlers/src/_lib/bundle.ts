// Bundles each handler src/<slug>.ts into functions/<slug>/handler.gen.js (ESM, no Node built-ins), so a
// function folder is self-contained when infra/deploy/deploy.sh copies it into the workspace functions.git.
//   pnpm --dir shared/handlers bundle            # every functions/<slug>/ that has a matching src/<slug>.ts
//   pnpm --dir shared/handlers bundle me         # one function
import { build, type BuildOptions } from "esbuild";
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const ROOT = join(here, "../../../..");
export const SRC = join(here, "..");
export const FUNCTIONS = join(ROOT, "functions");
export const BANNER = "// GENERATED by `pnpm --dir shared/handlers bundle` from shared/handlers/src/<slug>.ts + shared/core. Do not edit.";

export const bundleOptions = (slug: string): BuildOptions => ({
  entryPoints: [join(SRC, `${slug}.ts`)],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2020",
  mainFields: ["module", "main"],
  legalComments: "none",
  banner: { js: BANNER },
  write: false,
  logLevel: "silent",
});

/** The bundle text for one handler (used by `bundle` and by the freshness tests). */
export async function bundleText(slug: string): Promise<string> {
  const r = await build(bundleOptions(slug));
  return r.outputFiles![0]!.text;
}

export function deployableSlugs(): string[] {
  if (!existsSync(FUNCTIONS)) return [];
  return readdirSync(FUNCTIONS, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(FUNCTIONS, d.name, "config.json")) && existsSync(join(SRC, `${d.name}.ts`)))
    .map((d) => d.name)
    .sort();
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = process.argv.slice(2);
  const slugs = want.length ? want : deployableSlugs();
  for (const slug of slugs) {
    if (!existsSync(join(SRC, `${slug}.ts`))) throw new Error(`no handler src/${slug}.ts`);
    if (!existsSync(join(FUNCTIONS, slug, "config.json"))) throw new Error(`no functions/${slug}/config.json`);
    const text = await bundleText(slug);
    writeFileSync(join(FUNCTIONS, slug, "handler.gen.js"), text);
    console.log(`bundled functions/${slug}/handler.gen.js (${(text.length / 1024).toFixed(0)} KB)`);
  }
}
