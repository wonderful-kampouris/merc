"""Mirror purpose + rules of spec/contracts/llm/*.json into src/rules.generated.ts.
The @merc/contracts llm export keeps only name/profile/used_by/input/output, so
callStructured needs this to put the contract rules in the prompt.
Run: python3 -I shared/llm/scripts/gen-rules.py  (test/rules.test.ts checks drift)."""
import json, pathlib, sys
here = pathlib.Path(sys.argv[0]).resolve().parent.parent
spec = here.parent.parent / "spec" / "contracts" / "llm"
out = {}
for f in sorted(spec.glob("*.json")):
    d = json.loads(f.read_text(encoding="utf-8"))
    out[d["name"]] = {"purpose": d.get("purpose", ""), "rules": d.get("rules", [])}
body = json.dumps(out, ensure_ascii=False, indent=2)
(here / "src" / "rules.generated.ts").write_text(
    "// GENERATED by shared/llm/scripts/gen-rules.py from spec/contracts/llm/*.json. Do not edit.\n"
    f"export const llmRules: Record<string, {{ purpose: string; rules: string[] }}> = {body};\n",
    encoding="utf-8")
print(f"wrote {len(out)} rule sets")
