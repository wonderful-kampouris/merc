// Generates src/generated/tables.ts (typed rows + meta per table, role permissions) from spec/contracts,
// and vendors @merc/contracts generated types+schemas into src/generated/contracts/ so this lib has no
// path dependency outside itself (it ships as the workspace Shared Library utils/merc_core/, per S9).
import { readFileSync, writeFileSync, readdirSync, mkdirSync, copyFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const contracts = join(root, "spec/contracts");
const outDir = join(here, "../src/generated");
const read = (p: string) => JSON.parse(readFileSync(p, "utf8"));
const pascal = (s: string) => s.split("_").map((p) => p[0]!.toUpperCase() + p.slice(1)).join("");

const TS: Record<string, string> = { string: "string", auto_uuid: "string", date: "string", datetime: "string", number: "number", boolean: "boolean" };

const order: string[] = read(join(contracts, "tables/_order.json")).order;
const names = readdirSync(join(contracts, "tables")).filter((f) => f.endsWith(".json") && !f.startsWith("_")).map((f) => f.slice(0, -5)).sort();

interface Col { name: string; type: string; required?: boolean; primary_key?: boolean; reference?: { table: string; on_delete?: string } }
const pkOf = (t: string): string => {
  const cols: Col[] = read(join(contracts, "tables", `${t}.json`)).create.columns;
  const pk = cols.find((c) => c.primary_key);
  if (!pk) throw new Error(`${t}: no primary_key column`);
  return pk.name;
};
/** A FK always targets the referenced table's PK; restrict is the platform default when on_delete is omitted. */
function refMeta(n: string, c: Col) {
  const [schema, table] = c.reference!.table.includes(".") ? c.reference!.table.split(".") : ["merc", c.reference!.table];
  if (schema !== "merc") throw new Error(`${n}.${c.name}: reference outside schema merc (${c.reference!.table})`);
  if (!names.includes(table!)) throw new Error(`${n}.${c.name}: reference to unknown table ${table}`);
  return { table: table!, column: pkOf(table!), on_delete: c.reference!.on_delete ?? "restrict" };
}

let types = "";
const meta: Record<string, unknown> = {};
for (const n of names) {
  const { create, x } = read(join(contracts, "tables", `${n}.json`));
  // Platform shape (WP-INF-03): per-column `primary_key: true`, `reference: {table: "merc.<t>", on_delete}`.
  const pks = create.columns.filter((c: Col) => c.primary_key).map((c: Col) => c.name);
  if (pks.length !== 1) throw new Error(`${n}: expected exactly one primary_key column, got ${pks.length}`);
  const pk: string = pks[0];
  const enums: Record<string, string[]> = x.enums ?? {};
  const cols: Record<string, unknown> = {};
  let row = "", ins = "";
  for (const c of create.columns) {
    const t = TS[c.type];
    if (!t) throw new Error(`${n}.${c.name}: unknown column type ${c.type}`);
    const ty = enums[c.name] ? enums[c.name]!.map((v) => JSON.stringify(v)).join(" | ") : t;
    row += c.required ? `  ${c.name}: ${ty};\n` : `  ${c.name}?: ${ty} | null;\n`;
    const autoPk = c.name === pk && c.type === "auto_uuid";
    const insRequired = c.required && !autoPk && c.name !== "org_id";
    ins += insRequired ? `  ${c.name}: ${ty};\n` : `  ${c.name}?: ${ty} | null;\n`;
    cols[c.name] = {
      type: c.type,
      required: !!c.required,
      ...(enums[c.name] ? { enum: enums[c.name] } : {}),
      ...(c.reference ? { ref: refMeta(n, c) } : {}),
    };
  }
  for (const k of Object.keys(enums)) if (!cols[k]) throw new Error(`${n}: enum for unknown column ${k}`);
  types += `/** ${create.description} */\nexport interface ${pascal(n)}Row {\n${row}}\nexport interface ${pascal(n)}Insert {\n${ins}}\n\n`;
  meta[n] = {
    name: n,
    schema: create.schema,
    pk,
    pkAuto: create.columns.find((c: Col) => c.name === pk).type === "auto_uuid",
    orgScoped: create.columns.some((c: { name: string }) => c.name === "org_id"),
    columns: cols,
    unique: create.indexes.filter((i: { unique: boolean }) => i.unique).map((i: { columns: string[] }) => i.columns),
  };
}

const app = read(join(contracts, "app/app.json"));
const src = `// GENERATED by scripts/generate.ts from spec/contracts. Do not edit.
export const MERC_SCHEMA = "merc";

${types}export interface TableRows {
${names.map((n) => `  ${n}: ${pascal(n)}Row;`).join("\n")}
}
export interface TableInserts {
${names.map((n) => `  ${n}: ${pascal(n)}Insert;`).join("\n")}
}
export type TableName = keyof TableRows;

export interface ColumnMeta {
  type: "string" | "auto_uuid" | "date" | "datetime" | "number" | "boolean";
  required: boolean;
  enum?: readonly string[];
  ref?: { table: string; column: string; on_delete: string };
}
export interface TableMeta {
  name: TableName;
  schema: string;
  pk: string;
  pkAuto: boolean;
  orgScoped: boolean;
  columns: Record<string, ColumnMeta>;
  unique: string[][];
}

export const TABLES: { readonly [N in TableName]: TableMeta } = ${JSON.stringify(meta, null, 1)} as any;

export const TABLE_ORDER: readonly TableName[] = ${JSON.stringify(order)};

export type RoleCode = "rep" | "manager" | "admin";
/** contracts/app/app.json roles: permissions granted to all rows, and per relation. */
export const ROLE_PERMISSIONS: { readonly [R in RoleCode]: { all: readonly string[]; relation: Readonly<Record<string, readonly string[]>> } } = ${JSON.stringify(app.roles)};
`;

mkdirSync(join(outDir, "contracts"), { recursive: true });
writeFileSync(join(outDir, "tables.ts"), src);
const pc = join(root, "packages/contracts/src/generated");
for (const f of ["types.ts", "schemas.ts"]) copyFileSync(join(pc, f), join(outDir, "contracts", f));
console.log(`generated ${names.length} tables, ${Object.keys(app.roles).length} roles; vendored contracts types+schemas`);
